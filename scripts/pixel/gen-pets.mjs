/**
 * The frame data of the sheets script animates (SPEC 3.2, 3.7): the mascot
 * pet, which the pet controller plays on the shared ticker, and the mini-me
 * ride, which the wallpaper canvas draws on the road.
 *
 *   pnpm art:pets            write src/components/os/pets/sheet-data.generated.ts
 *   pnpm art:pets --check    fail if it is stale
 *
 * From each export (`src/assets/pixel/pets/<sheet>.json`) it keeps what the
 * code reads and nothing else, so the page never ships the Aseprite JSON:
 * the frame size, the sheet size, each tag's frames as `[x, y, ms]` on the
 * sheet in the order they play, whether the tag plays once (`repeat`), and
 * the pet's `pivot` and `hitbox` slices.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

import { flag, formatSource, isMain } from './cli.mjs'
import { ROOT } from './export-art.mjs'
import { readSheetJson, sliceKey, tagFrames } from './sheet.mjs'

const PETS_DIR = join(ROOT, 'src', 'assets', 'pixel', 'pets')
const DEFAULT_MODULE = join(
  ROOT,
  'src',
  'components',
  'os',
  'pets',
  'sheet-data.generated.ts'
)

/** The sheets, by the constant they are written as. */
const SHEETS = [
  { constant: 'PET_SHEET', name: 'mascot-pet', slices: ['pivot', 'hitbox'] },
  { constant: 'RIDE_SHEET', name: 'minime-ride', slices: [] },
]

/** One sheet's data as the module holds it. */
export function sheetData(data, sliceNames = []) {
  const { w, h } = data.frames[0].sourceSize
  if (data.frames.some((f) => f.trimmed)) {
    throw new Error('trimmed frames cannot be placed by their sheet rectangle')
  }
  const tags = {}
  for (const tag of data.meta.frameTags) {
    tags[tag.name] = {
      frames: tagFrames(tag).map((i) => {
        const { x, y } = data.frames[i].frame
        return [x, y, data.frames[i].duration]
      }),
      once: tag.repeat === '1',
    }
  }
  const slices = {}
  for (const name of sliceNames) {
    const slice = data.meta.slices.find((s) => s.name === name)
    if (!slice) throw new Error(`no "${name}" slice`)
    const { bounds, pivot } = sliceKey(slice, 0)
    slices[name] = pivot
      ? { x: bounds.x + pivot.x, y: bounds.y + pivot.y }
      : { ...bounds }
  }
  return {
    frame: { w, h },
    size: { w: data.meta.size.w, h: data.meta.size.h },
    ...slices,
    tags,
  }
}

/** The module source for every sheet in `dir`. */
export async function petModule(dir = PETS_DIR, file = DEFAULT_MODULE) {
  const blocks = SHEETS.map(({ constant, name, slices }) => {
    const json = join(dir, `${name}.json`)
    const data = sheetData(readSheetJson(json), slices)
    return [
      `/** \`${name}\`: ${Object.keys(data.tags).join(', ')}. */`,
      `export const ${constant} = ${JSON.stringify(data)} as const`,
    ].join('\n')
  })
  const code = [
    '/**',
    ` * GENERATED by scripts/pixel/gen-pets.mjs from the ${SHEETS.map((s) => s.name).join(' and ')} exports.`,
    ' * Do not edit by hand: re-export the art and run `pnpm art:pets`.',
    ' *',
    ' * Sizes in art px; a frame is `[x, y, ms]`, its corner on the sheet and how',
    ' * long it shows, in the order its tag plays.',
    ' */',
    '',
    ...blocks.flatMap((block) => [block, '']),
  ].join('\n')
  return formatSource(code, file)
}

async function main(argv) {
  const file = flag(argv, '--out', DEFAULT_MODULE)
  const source = await petModule(flag(argv, '--in', PETS_DIR), file)
  const where = relative(ROOT, file).split('\\').join('/')
  if (argv.includes('--check')) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== source) {
      console.error(`${where} is stale. Run: pnpm art:pets`)
      process.exit(1)
    }
    console.log(`${where} up to date`)
    return
  }
  writeFileSync(file, source)
  console.log(`wrote ${where}`)
}

if (isMain(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
