/**
 * The custom cursors as CSS (SPEC 2.4, Cursors): `grab` and `grabbing`, for
 * title bars (and the pet, later).
 *
 *   pnpm art:cursors            write src/styles/pixel-cursors.css
 *   pnpm art:cursors --check    fail if that file is stale
 *   node scripts/pixel/gen-cursors.mjs --in <sheet.json> --out <file.css>
 *
 * Atlas contract (os-cursors.aseprite, exported by `pnpm art:export`): one
 * slice per cursor, named after the CSS keyword it stands in for, with its
 * hotspot as the slice pivot.
 *
 * An art pixel is at least 2 CSS px, so a 16x16 cursor is shown at 32 CSS px:
 * the 1x image is the art at 2x (32 px) and the 2x image the art at 4x
 * (64 px), both scaled by whole pixels with no smoothing. At DPR 1 a 16 px
 * file would draw the cursor at half the scale of everything around it.
 *
 * The images are PNG data URIs (a few hundred bytes each; CSP allows `data:`
 * images): no request, nothing in `public/` (served `no-store`), and the
 * same in every bundler. Each rule falls back to a plain 1x `url()` and then
 * to the system keyword, so a browser that cannot draw the image still
 * shows a hand. The `:active` rule shows `grabbing` while the pointer is
 * down on a grab target.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import sharp from 'sharp'

import { isMain } from './cli.mjs'
import { ROOT } from './export-art.mjs'
import { cssName } from './gen-sprites.mjs'
import { loadSheet, pixelAt, sliceKey } from './sheet.mjs'

const DEFAULT_IN = join(
  ROOT,
  'src',
  'assets',
  'pixel',
  'cursors',
  'os-cursors.json'
)
const DEFAULT_OUT = join(ROOT, 'src', 'styles', 'pixel-cursors.css')

/** CSS px per art px at DPR 1, and the scales of the 1x and 2x images. */
const SCALES = [2, 4]

/** A slice of frame 0 as a PNG at `scale`, nearest neighbour. */
async function slicePng(sheet, bounds, scale) {
  const raw = Buffer.alloc(bounds.w * bounds.h * 4)
  for (let y = 0; y < bounds.h; y++) {
    for (let x = 0; x < bounds.w; x++) {
      raw.set(
        pixelAt(sheet, 0, bounds.x + x, bounds.y + y),
        (y * bounds.w + x) * 4
      )
    }
  }
  return sharp(raw, { raw: { width: bounds.w, height: bounds.h, channels: 4 } })
    .resize(bounds.w * scale, bounds.h * scale, { kernel: 'nearest' })
    .png({ palette: true, colours: 16, dither: 0, compressionLevel: 9 })
    .toBuffer()
}

function dataUri(png) {
  return `url("data:image/png;base64,${png.toString('base64')}")`
}

/** The declarations of one cursor. */
async function cursorLines(sheet, slice) {
  const key = sliceKey(slice, 0)
  if (!key.pivot) throw new Error(`cursor "${slice.name}" has no pivot`)
  const keyword = slice.name
  const [one, two] = await Promise.all(
    SCALES.map((scale) => slicePng(sheet, key.bounds, scale))
  )
  // The hotspot in CSS px of the 1x image, which both images are drawn at.
  const hot = `${key.pivot.x * SCALES[0]} ${key.pivot.y * SCALES[0]}`
  const set = `${dataUri(one)} 1x, ${dataUri(two)} 2x`
  return [
    `cursor: ${dataUri(one)} ${hot}, ${keyword};`,
    `cursor: -webkit-image-set(${set}) ${hot}, ${keyword};`,
    `cursor: image-set(${set}) ${hot}, ${keyword};`,
  ]
}

/** The whole stylesheet for a loaded cursor sheet. */
export async function cursorsCss(
  sheet,
  source = 'src/assets/pixel/cursors/os-cursors.json'
) {
  const slices = [...sheet.data.meta.slices].sort((a, b) =>
    a.name.localeCompare(b.name)
  )
  if (slices.length === 0) throw new Error(`${sheet.json}: no slices`)
  const lines = new Map()
  for (const slice of slices) {
    if (cssName(slice.name) !== slice.name) {
      throw new Error(`cursor "${slice.name}" is not kebab case`)
    }
    lines.set(slice.name, await cursorLines(sheet, slice))
  }
  const rule = (selector, body) =>
    `${selector} {\n${body.map((l) => `  ${l}`).join('\n')}\n}`
  const blocks = [...lines].map(([name, body]) =>
    rule(`.px-cursor-${name}`, body)
  )
  if (lines.has('grab') && lines.has('grabbing')) {
    blocks.push(rule('.px-cursor-grab:active', lines.get('grabbing')))
  }
  return [
    '/*',
    ` * GENERATED by scripts/pixel/gen-cursors.mjs from ${source}.`,
    ' * Do not edit by hand: re-export the cursor atlas and run `pnpm art:cursors`.',
    ' */',
    '',
    blocks.join('\n\n'),
    '',
  ].join('\n')
}

async function main(argv) {
  const at = (flag, fallback) => {
    const i = argv.indexOf(flag)
    return i > -1 ? argv[i + 1] : fallback
  }
  const input = at('--in', DEFAULT_IN)
  const out = at('--out', DEFAULT_OUT)
  if (!existsSync(input)) {
    console.error(
      `${relative(ROOT, input)} does not exist yet. Run: pnpm art:export --only cursors`
    )
    process.exit(1)
  }
  const sheet = await loadSheet(input)
  const css = await cursorsCss(
    sheet,
    relative(ROOT, input).split('\\').join('/')
  )
  const count = sheet.data.meta.slices.length
  if (argv.includes('--check')) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== css) {
      console.error(`${relative(ROOT, out)} is stale. Run: pnpm art:cursors`)
      process.exit(1)
    }
    console.log(`cursors up to date: ${count}`)
    return
  }
  writeFileSync(out, css)
  console.log(
    `wrote ${relative(ROOT, out)}: ${count} cursor(s), ${css.length} bytes`
  )
}

if (isMain(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message)
    process.exit(1)
  })
}
